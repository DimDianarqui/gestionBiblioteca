import os
from datetime import date

# =========================================================
# ACCESO A DATOS (archivos de texto)
# =========================================================
class RepositorioArchivo:
    def __init__(self, nombreArchivo):
        os.makedirs("datos", exist_ok=True)
        self.rutaArchivo = os.path.join("datos", nombreArchivo)
        if not os.path.exists(self.rutaArchivo):
            open(self.rutaArchivo, "w").close()

    def leerTodo(self):
        listaRegistros = []
        with open(self.rutaArchivo, "r", encoding="utf-8") as archivo:
            for linea in archivo:
                linea = linea.strip()
                if linea:
                    listaRegistros.append(linea.split("|"))
        return listaRegistros

    def guardarTodo(self, listaRegistros):
        with open(self.rutaArchivo, "w", encoding="utf-8") as archivo:
            for registro in listaRegistros:
                archivo.write("|".join(registro) + "\n")

    def agregar(self, registro):
        with open(self.rutaArchivo, "a", encoding="utf-8") as archivo:
            archivo.write("|".join(registro) + "\n")


# =========================================================
# LÓGICA DE NEGOCIO
# =========================================================
class BibliotecaServicio:
    def __init__(self):
        self.repoUsuarios = RepositorioArchivo("usuarios.txt")    # id|nombre|telefono|correo
        self.repoLibros = RepositorioArchivo("libros.txt")        # id|titulo|categoria|totales|disponibles
        self.repoPrestamos = RepositorioArchivo("prestamos.txt")  # id|idUsuario|idLibro|fechaPrestamo|estado

    # ---------- Usuarios ----------
    def registrarUsuario(self, nombre, telefono, correo):
        nuevoId = str(len(self.repoUsuarios.leerTodo()) + 1)
        self.repoUsuarios.agregar([nuevoId, nombre, telefono, correo])
        return nuevoId

    def listarUsuarios(self):
        return self.repoUsuarios.leerTodo()

    # ---------- Libros ----------
    def registrarLibro(self, titulo, categoria, totalEjemplares):
        nuevoId = str(len(self.repoLibros.leerTodo()) + 1)
        self.repoLibros.agregar([nuevoId, titulo, categoria, totalEjemplares, totalEjemplares])
        return nuevoId

    def listarLibros(self):
        return self.repoLibros.leerTodo()

    # ---------- Préstamos ----------
    def prestarLibro(self, idUsuario, idLibro):
        listaLibros = self.repoLibros.leerTodo()
        for libro in listaLibros:
            if libro[0] == idLibro:
                if int(libro[4]) <= 0:
                    return False, "No hay ejemplares disponibles"
                libro[4] = str(int(libro[4]) - 1)
                self.repoLibros.guardarTodo(listaLibros)
                nuevoId = str(len(self.repoPrestamos.leerTodo()) + 1)
                self.repoPrestamos.agregar([nuevoId, idUsuario, idLibro, str(date.today()), "ACTIVO"])
                return True, "Préstamo registrado"
        return False, "Libro no encontrado"

    def devolverLibro(self, idPrestamo):
        listaPrestamos = self.repoPrestamos.leerTodo()
        for prestamo in listaPrestamos:
            if prestamo[0] == idPrestamo and prestamo[4] == "ACTIVO":
                prestamo[4] = "DEVUELTO"
                self.repoPrestamos.guardarTodo(listaPrestamos)

                listaLibros = self.repoLibros.leerTodo()
                for libro in listaLibros:
                    if libro[0] == prestamo[2]:
                        libro[4] = str(int(libro[4]) + 1)
                self.repoLibros.guardarTodo(listaLibros)
                return True, "Devolución registrada"
        return False, "Préstamo no encontrado o ya devuelto"

    def listarPrestamosActivos(self):
        return [p for p in self.repoPrestamos.leerTodo() if p[4] == "ACTIVO"]

    def historialUsuario(self, idUsuario):
        listaHistorial = [p for p in self.repoPrestamos.leerTodo() if p[1] == idUsuario]
        listaHistorial.sort(key=lambda p: p[3])  # orden cronológico
        return listaHistorial


